import { Helmet } from 'react-helmet-async';
import { canonical } from '../utils/seo.js';
import { BUSINESS } from '../utils/constants.js';

/**
 * Per-page title, description, canonical, Open Graph tags and JSON-LD.
 */
export default function Seo({ title, description, path = '/', image = '/og-image.jpg', schemas = [], noindex = false }) {
  const url = canonical(path);
  return (
    <Helmet prioritizeSeoTags>
      <title>{title}</title>
      <meta name="description" content={description} />
      <link rel="canonical" href={url} />
      {noindex && <meta name="robots" content="noindex, nofollow" />}

      <meta property="og:type" content="website" />
      <meta property="og:site_name" content={BUSINESS.name} />
      <meta property="og:title" content={title} />
      <meta property="og:description" content={description} />
      <meta property="og:url" content={url} />
      <meta property="og:image" content={`${canonical('')}${image}`} />
      <meta property="og:locale" content="en_IN" />

      <meta name="twitter:card" content="summary_large_image" />
      <meta name="twitter:title" content={title} />
      <meta name="twitter:description" content={description} />

      {schemas.map((schema, i) => (
        <script key={i} type="application/ld+json">{JSON.stringify(schema)}</script>
      ))}
    </Helmet>
  );
}
